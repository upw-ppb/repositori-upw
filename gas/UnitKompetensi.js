var STOP_NAMA_MK = ["praktik", "pengelolaan", "dan", "the", "of"];
function kataNamaMk(s) {
  return String(s || "").toLowerCase().replace(/&/g, " dan ").replace(/[^a-z0-9 ]/g, " ").split(/\s+/).filter(function (w) { return w.length > 2 && STOP_NAMA_MK.indexOf(w) < 0; });
}
/** Unit bawaan untuk nama MK (kemiripan kata nama ≥ 0,6). */
function unitMkBawaan(nama) {
  var a = kataNamaMk(nama), terbaik = null, skor = 0;
  if (!a.length) return [];
  Object.keys(UNIT_MK_2023).forEach(function (k) {
    var b = kataNamaMk(k), sama = a.filter(function (w) { return b.indexOf(w) >= 0; }).length, gab = a.length + b.length - sama, s = gab ? sama / gab : 0;
    if (s > skor) { skor = s; terbaik = k; }
  });
  return skor >= 0.6 ? UNIT_MK_2023[terbaik].map(function (u) { return { k: u.k, en: u.en, id: u.id || "" }; }) : [];
}
